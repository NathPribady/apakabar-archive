#!/usr/bin/env python3
"""Fit the "about" model and write src/model.rs.

Inputs
  features.jsonl  one line per (message, theme mentioned), as written by
                  `apakabar features --ids <ids> --out features.jsonl`
  verdicts*.jsonl hand-checked verdicts, one JSON object per line:
                  {"set": "theme:<slug>" or "about:<slug>[/round]", "ak_id": ..., "verdict": "yes"|"no"|"unsure"}
                  (the "verdicts" list of tools/first_pass_checks.json, written out one per line)

The model is a logistic regression (scikit-learn, C=1) over the features in
tagger::ThemeHits::features. Each theme gets its own threshold: the lowest of
0.75, 0.80, 0.85, 0.90 at which the cross-validated precision (10 x 10-fold) is
at least 92% with five or more messages kept; for a theme with fewer than five
messages above every threshold, the lowest threshold from 0.80 at which all of
three or more are correct; otherwise 0.90.

  python3 tools/fit_model.py --features features.jsonl --verdicts verdicts_*.jsonl --out src/model.rs
"""
import argparse, datetime, json, sys
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_predict

FEATURES = ["title has a term", "ln(1+title weak words)", "ln(1+hits in the first two paragraphs)",
            "ln(1+hits per 1000 words)", "share of paragraphs with hits", "ln(1+hits)", "ln(1+terms)",
            "ln(1+words)", "ln(1+paragraphs with hits)", "ln(1+hits in the busiest paragraph)",
            "ln(1+themes mentioned)", "digest"]
GRID = [0.75, 0.8, 0.85, 0.9]

ap = argparse.ArgumentParser()
ap.add_argument("--features", required=True)
ap.add_argument("--verdicts", nargs="+", required=True)
ap.add_argument("--themes", required=True, help="theme slugs in lexicon order, comma-separated")
ap.add_argument("--out", required=True)
ap.add_argument("--override", action="append", default=[], help="slug=threshold, set by hand after a check round (the weights are unchanged)")
a = ap.parse_args()
themes = a.themes.split(",")

F = {}
for l in open(a.features):
    d = json.loads(l)
    F[(d["ak_id"], d["theme"])] = d["x"]
rows = []
for fn in a.verdicts:
    for l in open(fn):
        v = json.loads(l)
        kind, _, rest = v["set"].partition(":")
        if kind not in ("theme", "about") or v["verdict"] not in ("yes", "no"):
            continue
        slug = rest.split("/")[0]
        x = F.get((v["ak_id"], slug))
        if x is not None:
            rows.append((slug, x, 1 if v["verdict"] == "yes" else 0))
X = np.array([r[1] for r in rows]); y = np.array([r[2] for r in rows]); slugs = np.array([r[0] for r in rows])
assert X.shape[1] == len(FEATURES) + len(themes), X.shape

P = np.zeros(len(y))
for seed in range(10):
    P += cross_val_predict(LogisticRegression(max_iter=5000, C=1.0), X, y,
                           cv=StratifiedKFold(10, shuffle=True, random_state=seed), method="predict_proba")[:, 1]
P /= 10

th, report = {}, []
for s in themes:
    m = slugs == s
    pick = None
    stats = []
    for t in GRID:
        sel = m & (P >= t)
        k = int(sel.sum()); pr = float(y[sel].mean()) if k else 0.0
        stats.append((t, k, pr))
        if pick is None and k >= 5 and pr >= 0.92:
            pick = t
    if pick is None and all(k < 5 for _, k, _ in stats):
        pick = next((t for t, k, pr in stats if t >= 0.8 and k >= 3 and pr == 1.0), None)
    th[s] = pick if pick is not None else 0.9
    k, pr = next((k, pr) for t, k, pr in stats if t == th[s])
    report.append(f"//   {s:<18} {th[s]:.2f}  ({k} of {int(m.sum())} checked messages above it, {pr:.0%} correct)")

overrides = dict((o.split("=")[0], float(o.split("=")[1])) for o in a.override)
for k, v in overrides.items():
    assert k in th, k
    th[k] = v
    report = [r if not r.startswith(f"//   {k:<18}") else f"//   {k:<18} {v:.2f}  (set after the second precision check, from all checked messages)" for r in report]

clf = LogisticRegression(max_iter=5000, C=1.0).fit(X, y)
w, b = clf.coef_[0], float(clf.intercept_[0])
sel = np.array([P[i] >= th[slugs[i]] for i in range(len(y))])
prec, rec = float(y[sel].mean()), float(y[sel].sum() / y.sum())

names = FEATURES + [f"theme: {s}" for s in themes]
out = [
    "//! The \"about\" model: a logistic regression over the pattern of a theme's words in a message",
    "//! (see `tagger::ThemeHits::features`). A message mentions a theme when the theme's words",
    "//! pass the rules in `tagger`; it is about the theme when the model's score reaches the",
    "//! theme's threshold.",
    "//!",
    f"//! Generated by tools/fit_model.py on {datetime.date.today().isoformat()} from {len(y)} hand-checked",
    f"//! (message, theme) pairs ({int(y.sum())} judged about the theme). Do not edit by hand: re-run the",
    "//! script after changing the lexicon or the features.",
    "//!",
    f"//! Cross-validated on the checked pairs, the thresholds below keep {sel.sum()} of them with",
    f"//! {prec:.1%} precision and {rec:.1%} recall. Fresh samples drawn from the about tier are the",
    "//! real test (see the precision checks in the editors' pages).",
    "",
    "/// Weights, in the order of `tagger::ThemeHits::features`.",
    f"pub static WEIGHTS: [f64; {len(w)}] = [",
]
for name, v in zip(names, w):
    out.append(f"    {v:.6f}, // {name}")
out += ["];", f"pub const INTERCEPT: f64 = {b:.6f};", "",
        "/// Score at which a message counts as about each theme, chosen by cross-validation:",
        "//   theme              threshold"]
out += report
out += ["pub static THRESHOLDS: &[(&str, f64)] = &["]
out += [f"    (\"{s}\", {th[s]:.2f})," for s in themes]
out += ["];", "pub const DEFAULT_THRESHOLD: f64 = 0.9;", "",
        "pub fn threshold(slug: &str) -> f64 {",
        "    THRESHOLDS.iter().find(|(s, _)| *s == slug).map(|t| t.1).unwrap_or(DEFAULT_THRESHOLD)",
        "}", "",
        "pub fn score(x: &[f64]) -> f64 {",
        "    let z: f64 = INTERCEPT + x.iter().zip(WEIGHTS.iter()).map(|(a, b)| a * b).sum::<f64>();",
        "    1.0 / (1.0 + (-z).exp())",
        "}", ""]
open(a.out, "w").write("\n".join(out))
print(f"wrote {a.out}: {len(y)} pairs, cv precision {prec:.3f}, recall {rec:.3f}", file=sys.stderr)
print("\n".join(report), file=sys.stderr)
